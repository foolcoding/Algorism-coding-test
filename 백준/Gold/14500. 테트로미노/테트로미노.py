import sys
input = sys.stdin.readline

n, m = map(int, input().split())
arr = [list(map(int, input().split())) for _ in range(n)]

shapes = [
    # 일자
    [(0,0),(0,1),(0,2),(0,3)],
    [(0,0),(1,0),(2,0),(3,0)],
    # 사각형
    [(0,0),(0,1),(1,0),(1,1)],
    # L / J
    [(0,0),(1,0),(2,0),(2,1)],
    [(0,1),(1,1),(2,1),(2,0)],
    [(0,0),(0,1),(1,0),(2,0)],
    [(0,0),(0,1),(1,1),(2,1)],
    [(0,0),(0,1),(0,2),(1,0)],
    [(0,0),(0,1),(0,2),(1,2)],
    [(0,2),(1,0),(1,1),(1,2)],
    [(0,0),(1,0),(1,1),(1,2)],
    # S / Z (4)
    [(0,0),(0,1),(1,1),(1,2)],
    [(0,1),(0,2),(1,0),(1,1)],
    [(0,0),(1,0),(1,1),(2,1)],
    [(0,1),(1,0),(1,1),(2,0)],

    [(0,0),(0,1),(0,2),(1,1)],  # ㅗ
    [(1,0),(1,1),(1,2),(0,1)],  # ㅜ
    [(0,0),(1,0),(2,0),(1,1)],  # ㅓ
    [(0,1),(1,1),(2,1),(1,0)],  # ㅏ
]

result = 0
for y in range(n):
    for x in range(m):
        for shape in shapes:
            ok = True
            s = 0
            for dy, dx in shape:
                ny, nx = y + dy, x + dx
                if not (0 <= ny < n and 0 <= nx < m):
                    ok = False
                    break
                s += arr[ny][nx]
            if ok and s > result:
                result = s
print(result)
